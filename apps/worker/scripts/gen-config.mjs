// The skail bundle cannot read environment variables, so the settings the commands need are written into
// src/build-config.generated.ts (git-ignored) at build time, from the environment or .env.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadEnv } from "./env.mjs";

const env = loadEnv();
const config = {
  webBaseUrl: env.WEB_BASE_URL || "http://localhost:8080",
  quoteProvider: (env.QUOTE_PROVIDER || "http").toLowerCase(),
  quoteApiUrl: env.QUOTE_API_URL || "https://economia.awesomeapi.com.br/",
};
const file = fileURLToPath(new URL("../src/build-config.generated.ts", import.meta.url));
writeFileSync(
  file,
  `// generated by scripts/gen-config.mjs; do not edit\nexport const buildConfig = ${JSON.stringify(config, null, 2)};\n`,
);
console.log(`worker config: web=${config.webBaseUrl} quotes=${config.quoteProvider}`);
